"""The committed gallery thumbnails: that they exist, decode, and stay in step with the code.

They are generated by hand (``tools/build_gallery_assets.py`` needs a GPU and a display), so
the test-suite's job is not to render them but to notice the ways the committed set can rot:
a preset or recipe added without regenerating, a file that no longer decodes, a scene the tool
and the panel disagree about, or a wheel that quietly ships tens of megabytes of PNG.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import numpy as np
import pytest

from glplot.gui import gallery_assets, recipes, styles

REPO = Path(__file__).resolve().parent.parent
TOOL = REPO / "tools" / "build_gallery_assets.py"

STYLE_PAIRS = [(k, s) for k in styles.STYLE_KEYS for s in gallery_assets.STYLE_SCENES]


@pytest.fixture(scope="module")
def tool():
    spec = importlib.util.spec_from_file_location("build_gallery_assets", TOOL)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class TestStyleThumbnails:
    @pytest.mark.parametrize("key,scene", STYLE_PAIRS, ids=lambda v: str(v))
    def test_every_style_has_a_render_of_every_scene(self, key, scene):
        path = gallery_assets.style_asset(key, scene)
        assert (
            path is not None
        ), f"regenerate: python tools/build_gallery_assets.py ({key}, {scene})"

    @pytest.mark.parametrize("key,scene", STYLE_PAIRS[::7], ids=lambda v: str(v))
    def test_a_render_decodes_to_the_card_shape_and_is_not_blank(self, key, scene):
        rgba = gallery_assets.load_rgba(gallery_assets.style_asset(key, scene))
        width, height = gallery_assets.THUMB_SIZE
        assert rgba.shape == (height, width, 4) and rgba.dtype == np.uint8
        assert float(rgba[..., :3].std()) > 3.0

    def test_a_render_actually_shows_the_styles_page(self):
        """Not a stock chart: the thumbnail's corner is the preset's own background."""
        for key in ("neon", "clean", "vintage"):
            style = styles.get_style(key)
            corner = gallery_assets.load_rgba(gallery_assets.style_asset(key, "lines"))[4, 4, :3]
            expected = np.array(style.background) * 255.0
            if style.gradient is not None:
                expected = np.array(style.gradient[0]) * 255.0
            assert np.abs(corner.astype(float) - expected).max() < 60.0, key


class TestRecipeThumbnails:
    @pytest.mark.parametrize("recipe", recipes.RECIPES, ids=lambda r: r.key)
    def test_every_recipe_has_a_render(self, recipe):
        assert gallery_assets.recipe_asset(recipe.key) is not None, recipe.key

    @pytest.mark.parametrize("recipe", recipes.RECIPES[::3], ids=lambda r: r.key)
    def test_a_recipe_render_decodes_and_is_not_blank(self, recipe):
        rgba = gallery_assets.load_rgba(gallery_assets.recipe_asset(recipe.key))
        assert rgba.shape[:2] == gallery_assets.THUMB_SIZE[::-1]
        assert float(rgba[..., :3].std()) > 3.0


class TestTheSetIsExactlyTheCurrentCatalogue:
    def test_no_orphans(self):
        """A removed preset or recipe leaves a file behind unless somebody deletes it."""
        expected = {f"{k}__{s}.webp" for k, s in STYLE_PAIRS}
        found = {p.name for p in (gallery_assets.ASSET_ROOT / "styles").glob("*.webp")}
        assert found == expected
        recipe_files = {p.name for p in (gallery_assets.ASSET_ROOT / "recipes").glob("*.webp")}
        assert recipe_files == {f"{k}.webp" for k in recipes.RECIPE_KEYS}

    def test_the_set_stays_small_enough_to_ship(self):
        total = sum(p.stat().st_size for p in gallery_assets.ASSET_ROOT.rglob("*.webp"))
        assert total < 3 * 1024 * 1024, f"{total / 1e6:.1f} MB of thumbnails"

    def test_the_tool_and_the_panel_agree_about_the_scenes(self, tool):
        assert tuple(tool.SCENES) == gallery_assets.STYLE_SCENES
        assert set(gallery_assets.SCENE_LABELS) == set(gallery_assets.STYLE_SCENES)

    def test_the_tool_stores_what_the_panel_expects(self, tool):
        assert tuple(tool.THUMB) == gallery_assets.THUMB_SIZE
        assert tool.ASSETS == gallery_assets.ASSET_ROOT

    def test_every_scene_is_ascii_named_and_labelled(self):
        for scene, label in gallery_assets.SCENE_LABELS.items():
            assert scene.isascii() and label.isascii()


class TestLoadingNeverRaises:
    def test_no_path(self):
        assert gallery_assets.load_rgba(None) is None

    def test_a_missing_file(self, tmp_path):
        assert gallery_assets.load_rgba(tmp_path / "nope.webp") is None

    def test_a_corrupt_file(self, tmp_path):
        bad = tmp_path / "bad.webp"
        bad.write_bytes(b"this is not an image")
        assert gallery_assets.load_rgba(bad) is None

    def test_unknown_scene_and_key(self):
        assert gallery_assets.style_asset("clean", "no-such-scene") is None
        assert gallery_assets.style_asset("no-such-style", "lines") is None
        assert gallery_assets.recipe_asset("no-such-recipe") is None

    def test_a_tiny_png_round_trips(self, tmp_path):
        from PIL import Image

        path = tmp_path / "x.png"
        Image.fromarray(np.full((3, 5, 3), 200, dtype=np.uint8)).save(path)
        rgba = gallery_assets.load_rgba(path)
        assert rgba.shape == (3, 5, 4) and int(rgba[0, 0, 3]) == 255
