@dataclass(frozen=True)
class _Tab:
    """A tab: its stable id (used by :meth:`HelpPanel.show`) and its label."""

    id: str
    title: str


_TABS: Tuple[_Tab, ...] = (
    _Tab("start", "Getting Started"),
    _Tab("keyboard", "Keyboard"),
    _Tab("expressions", "Expressions"),
    _Tab("panels", "Panels"),
    _Tab("tips", "Tips"),
)


class HelpPanel(Panel):
    """Teach the workstation: a tour, the live keymap, the expression reference, tips."""

    title = "Help"
    icon = "info"
    default_open = False

    def __init__(self, ws: Any) -> None:
        super().__init__(ws)
        self._query: str = ""
        self._active_tab: str = _TABS[0].id
        #: Set by :meth:`show`; consumed by the next frame's tab/section rendering.
        self._pending_tab: Optional[str] = None
        self._pending_section: Optional[str] = None
        self._status: str = ""
        # SAFE_NAMES is a module-level dict that never changes at runtime, so the ~70-row
        # reference is built once rather than per frame.
        self._expr_sections: Tuple[Section, ...] = ()

    # -- public API (the palette's "?" provider talks to this) --------------------------

    def topics(self) -> List[Tuple[str, str]]:
        """Every addressable Help topic as ``(topic_id, title)``.

        Topic ids are ``"<tab>"`` or ``"<tab>/<section title>"``; both are accepted by
        :meth:`show`. The palette's ``?`` provider lists these.
        """
        out: List[Tuple[str, str]] = []
        for tab in _TABS:
            out.append((tab.id, tab.title))
            for section in self._sections_for(tab.id):
                topic_id = "{0}/{1}".format(tab.id, section.title)
                out.append((topic_id, "{0} · {1}".format(tab.title, section.title)))
        return out

    def show(self, topic_id: Optional[str] = None, *, query: str = "") -> None:
        """Open Help at ``topic_id`` (from :meth:`topics`), optionally with a search query.

        Safe to call from a draw callback: it only sets state that the next frame reads.
        An unknown topic falls back to selecting the first tab rather than raising — a
        stale palette entry must not take the frame down.
        """
        self.ws.open["help"] = True
        self._query = query
        self._status = ""
        if not topic_id:
            return
        tab_id, _, section_title = topic_id.partition("/")
        self._pending_tab = tab_id if any(t.id == tab_id for t in _TABS) else _TABS[0].id
        self._pending_section = section_title or None

    #: The name the command palette's ``?`` provider probes for
    #: (``open_topic`` / ``show_topic`` / ``select_topic``, in that order). Aliased rather
    #: than renamed: ``show`` is what the workspace's Help actions call, and one method with
    #: two names cannot drift from itself the way two implementations would.
    open_topic = show

    # -- content assembly --------------------------------------------------------------

    def _sections_for(self, tab_id: str) -> Tuple[Section, ...]:
        """The sections of a tab. Generated ones are rebuilt per call; static ones are not."""
        if tab_id == "keyboard":
            return self._keyboard_sections()
        if tab_id == "expressions":
            if not self._expr_sections:
                self._expr_sections = _expression_sections()
            return self._expr_sections
        if tab_id == "panels":
            return _PANEL_SECTIONS
        if tab_id == "tips":
            return _TIPS
        return ()

    def _keyboard_sections(self) -> Tuple[Section, ...]:
        """Generate the shortcut sheet from the workspace's ActionRegistry.

        Only actions that actually carry a chord are listed: this is a keyboard sheet, and
        the palette is where the unbound ones live. Rebuilt every frame, which is what
        keeps it truthful — an action registered late, or a predicate that just disabled
        one, shows up immediately.
        """
        registry = getattr(self.ws, "registry", None)
        if registry is None:
            return (
                Section(
                    title="Keyboard",
                    intro=(
                        "No action registry is attached to this workspace, so there are no "
                        "registered shortcuts to list. The engine hotkeys below still work."
                    ),
                ),
                Section(
                    title="Engine hotkeys",
                    intro=_ENGINE_INTRO,
                    entries=_ENGINE_HOTKEYS,
                    value_header="Key",
                ),
            )

        sections: List[Section] = []
        try:
            actions = registry.all()
            categories = registry.categories()
        except Exception:  # pragma: no cover - defensive: a foreign registry object
            logger.exception("Could not read the action registry.")
            return (Section(title="Keyboard", intro="The action registry could not be read."),)

        for category in categories:
            entries = tuple(
                Entry(
                    label=action.title,
                    value=keys.format(action.chord),
                    note=action.description,
                )
                for action in actions
                if action.category == category and action.chord is not None
            )
            if entries:
                sections.append(Section(title=category, entries=entries, value_header="Shortcut"))

        try:
            conflicts = registry.conflicts()
        except Exception:  # pragma: no cover - defensive
            conflicts = []
        if conflicts:
            sections.append(
                Section(
                    title="Conflicts ({0})".format(len(conflicts)),
                    intro=(
                        "These chords are bound to more than one enabled action. Only the "
                        "first one listed ever runs; the others are dead until one of them "
                        "is rebound."
                    ),
                    entries=tuple(
                        Entry(
                            label=", ".join(a.title for a in group),
                            value=keys.format(chord),
                            note="Only '{0}' runs.".format(group[0].title),
                        )
                        for chord, group in conflicts
                    ),
                    value_header="Shortcut",
                )
            )

        sections.append(
            Section(
                title="Engine hotkeys",
                intro=_ENGINE_INTRO,
                entries=_ENGINE_HOTKEYS,
                value_header="Key",
            )
        )
        return tuple(sections)

    # -- actions the buttons perform ---------------------------------------------------

    def _open_panel(self, key: str) -> bool:
        """Open and focus panel ``key``. False (with a status line) when it does not exist."""
        panel = self.ws.panels.get(key)
        if panel is None:
            self._status = "The {0} panel is not available.".format(key)
            return False
        self.ws.open_panel(key)
        return True

    def _run_step(self, step: Step) -> None:
        """Perform a Getting Started step: its registered action, else open its panel.

        The action is preferred so the button and the shortcut cannot diverge. Its ``run``
        already routes any scene mutation through ``ws.queue`` (CONTRACT §1.1), which is
        why calling it from this draw callback is legitimate.
        """
        registry = getattr(self.ws, "registry", None)
        if step.action_id and registry is not None:
            try:
                action = registry.get(step.action_id)
                if action is not None and registry.enabled(action):
                    action.run()
                    self._status = "Ran: {0}".format(action.title)
                    return
            except Exception:
                logger.exception("Help step %r failed to run action %r", step.title, step.action_id)
        if step.panel and self._open_panel(step.panel):
            self._status = "Opened the {0} panel.".format(self.ws.panels[step.panel].title)

    def _insert_expression(self, snippet: str) -> None:
        """Drop ``snippet`` into the Functions panel's expression, then focus that panel.

        Appended, not inserted at a caret: imgui's ``input_text`` does not expose one. A
        separator is added when the existing text would otherwise be glued into nonsense
        (``a * sin(x)`` + ``exp(x)`` -> ``a * sin(x) + exp(x)``), so the result always
        parses and the user edits from something valid.
        """
        panel = self.ws.panels.get("functions")
        if panel is None:
            self._status = "The Functions panel is not available."
            return
        current = str(getattr(panel, "expr", "") or "").rstrip()
        if not current:
            new = snippet
        elif current[-1] in "+-*/(,%":
            new = "{0} {1}".format(current, snippet)
        else:
            new = "{0} + {1}".format(current, snippet)
        panel.expr = new
        self.ws.open_panel("functions")
        self._status = "Inserted {0} into Functions.".format(snippet)

    # -- search ------------------------------------------------------------------------

    @staticmethod
    def _matches(query: str, labels: Tuple[str, ...], prose: Tuple[str, ...] = ()) -> bool:
        """True when ``query`` hits any label (fuzzily) or any prose field (as a substring).

        The two rules are deliberately different. Fuzzy subsequence matching is right for a
        short identifier -- "mnm" should find ``minimum`` -- but over a paragraph it matches
        almost everything, because the letters of any short query appear scattered through
        any long English sentence: searching "paste" that way returned six of the seven
        tips, and "trig" pulled in "Round to nearest; ties go to even". Prose therefore
        requires real containment. Empty query matches everything.
        """
        if not query:
            return True
        for text in labels:
            if text and fuzzy.score(query, text) is not None:
                return True
        lowered = query.lower()
        for text in prose:
            if text and lowered in text.lower():
                return True
        return False

    def _filter(self, sections: Tuple[Section, ...]) -> List[Section]:
        """Drop entries and whole sections that the query does not reach.

        A section whose *title or intro* matches keeps all its entries: the user searched
        for the topic, not for a row inside it, and handing them an empty section would be
        a worse answer than the section itself.
        """
        query = self._query.strip()
        if not query:
            return list(sections)
        out: List[Section] = []
        for section in sections:
            if self._matches(query, (section.title,), (section.intro,)):
                out.append(section)
                continue
            entries = tuple(
                e for e in section.entries if self._matches(query, e.labels(), e.prose())
            )
            if entries:
                out.append(
                    Section(
                        title=section.title,
                        intro=section.intro,
                        entries=entries,
                        value_header=section.value_header,
                        value_width=section.value_width,
                        insertable=section.insertable,
                    )
                )
        return out

    # -- drawing -----------------------------------------------------------------------

    def draw(self) -> None:
        """Render the panel body. The workspace owns the surrounding window."""
        if not IMGUI_AVAILABLE:
            return
        self._draw_header()
        self._draw_tabs()

    def _draw_header(self) -> None:
        """The one-line pitch, the shortcut hints, and the cross-tab search box."""
        imgui.text_disabled(
            "F1 opens this panel · {0} opens the command palette".format(_chord_text("Mod+K"))
        )
        imgui.spacing()

        imgui.push_item_width(-88.0)
        changed, value = imgui.input_text("##help_search", self._query)
        imgui.pop_item_width()
        if changed:
            self._query = value
        imgui.same_line()
        if imgui.button("Clear", (74.0, 0.0)):
            self._query = ""
        # pyimgui 2.0's input_text has no placeholder/hint parameter, so the prompt lives
        # under the field rather than inside it.
        imgui.text_disabled("Search every tab: a function, a shortcut, a panel.")
        if self._status:
            imgui.text_disabled(self._status)
        imgui.separator()

    def _draw_tabs(self) -> None:
        """The tab bar; each tab scrolls its own child region."""
        tab_bar_open = imgui.begin_tab_bar("##help_tabs")
        if not tab_bar_open:
            return
        for tab in _TABS:
            flags = 0
            if self._pending_tab == tab.id:
                flags = imgui.TabItemFlags_.set_selected
            selected, _ = imgui.begin_tab_item(tab.title, flags=flags)
            if selected:
                if self._pending_tab == tab.id:
                    self._pending_tab = None
                self._active_tab = tab.id
                imgui.begin_child("##help_body_{0}".format(tab.id), (0.0, 0.0))
                try:
                    self._draw_tab_body(tab.id)
                finally:
                    # end_child is unconditional (CONTRACT §2.2); the try/finally makes that
                    # true even if a section raises mid-body.
                    imgui.end_child()
                imgui.end_tab_item()
        imgui.end_tab_bar()

    def _draw_tab_body(self, tab_id: str) -> None:
        """Dispatch a tab to its renderer. Everything but the tour is sections."""
        if tab_id == "start":
            self._draw_steps()
            return
        sections = self._filter(self._sections_for(tab_id))
        if tab_id == "expressions":
            imgui.push_text_wrap_pos(0.0)
            imgui.text_wrapped(_EXPR_INTRO)
            imgui.spacing()
            imgui.text_disabled(_EXPR_REDUCTION_NOTE)
            imgui.pop_text_wrap_pos()
            imgui.spacing()
        if not sections:
            imgui.text_disabled('Nothing here matches "{0}".'.format(self._query.strip()))
            return
        for section in sections:
            self._draw_section(section)

    def _draw_steps(self) -> None:
        """The Getting Started tour: numbered steps, each with a button that does it."""
        query = self._query.strip()
        steps = [s for s in _STEPS if self._matches(query, (s.title, s.button), (s.body,))]
        imgui.push_text_wrap_pos(0.0)
        imgui.text_wrapped(
            "Five steps from an empty window to a styled plot. Every button below really "
            "does the thing it describes — press it and watch where the panel opens."
        )
        imgui.pop_text_wrap_pos()
        imgui.spacing()
        if not steps:
            imgui.text_disabled('No step matches "{0}".'.format(query))
            return
        for index, step in enumerate(_STEPS):
            if step not in steps:
                continue
            imgui.push_id("help_step_{0}".format(index))
            imgui.text("{0}. {1}".format(index + 1, step.title))
            imgui.indent(14.0)
            imgui.push_text_wrap_pos(0.0)
            imgui.text_disabled(step.body)
            imgui.pop_text_wrap_pos()
            imgui.spacing()
            if imgui.button(step.button):
                self._run_step(step)
            imgui.unindent(14.0)
            imgui.spacing()
            imgui.separator()
            imgui.spacing()
            imgui.pop_id()

    def _draw_section(self, section: Section) -> None:
        """One collapsing header: intro prose, then the entry table."""
        # While a query is active every surviving section opens: results hidden inside a
        # collapsed header read as "no results".
        if self._query.strip() or self._pending_section == section.title:
            imgui.set_next_item_open(True)
        # Default open, every section: a Help tab that greets the reader with a column of
        # collapsed headers has hidden the answer behind a click they have no reason to
        # make. imgui remembers whatever they collapse themselves.
        expanded = imgui.collapsing_header(section.title, flags=imgui.TreeNodeFlags_.default_open)
        if self._pending_section == section.title:
            imgui.set_scroll_here_y(0.15)
            self._pending_section = None
        if not expanded:
            return

        imgui.indent(8.0)
        if section.intro:
            imgui.push_text_wrap_pos(0.0)
            imgui.text_disabled(section.intro)
            imgui.pop_text_wrap_pos()
            imgui.spacing()
        if section.entries:
            self._draw_entries(section)
        imgui.unindent(8.0)
        imgui.spacing()

    def _draw_entries(self, section: Section) -> None:
        """The two- or three-column entry table.

        ``begin_table`` returns False when it is clipped or out of space (CONTRACT
        §2.3), so ``end_table`` is called only inside the guard.
        """
        columns = 3 if section.insertable else 2
        flags = imgui.TableFlags_.row_bg | imgui.TableFlags_.borders_inner_h
        table_open = imgui.begin_table("##entries_{0}".format(section.title), columns, flags=flags)
        if not table_open:
            return
        try:
            if section.insertable:
                imgui.table_setup_column(
                    "Name", imgui.TableColumnFlags_.width_fixed, _SIGNATURE_COLUMN_W
                )
                imgui.table_setup_column("What it does", imgui.TableColumnFlags_.width_stretch)
                imgui.table_setup_column("", imgui.TableColumnFlags_.width_fixed, 62.0)
            else:
                imgui.table_setup_column("Action", imgui.TableColumnFlags_.width_stretch)
                imgui.table_setup_column(
                    section.value_header or "Key",
                    imgui.TableColumnFlags_.width_fixed,
                    section.value_width or _KEY_COLUMN_W,
                )
                if section.value_header:
                    imgui.table_headers_row()

            for index, entry in enumerate(section.entries):
                imgui.table_next_row()
                if section.insertable:
                    self._draw_insertable_row(section, index, entry)
                else:
                    self._draw_entry_row(entry)
        finally:
            imgui.end_table()

    @staticmethod
    def _draw_entry_row(entry: Entry) -> None:
        """A label (+ dimmed note beneath it) and its key column."""
        imgui.table_next_column()
        imgui.text(entry.label)
        if entry.note:
            imgui.push_text_wrap_pos(0.0)
            imgui.text_disabled(entry.note)
            imgui.pop_text_wrap_pos()
        imgui.table_next_column()
        imgui.text(entry.value)

    def _draw_insertable_row(self, section: Section, index: int, entry: Entry) -> None:
        """An expression row: signature, description, and an Insert button that means it."""
        imgui.table_next_column()
        imgui.text(entry.label)
        imgui.table_next_column()
        imgui.push_text_wrap_pos(0.0)
        imgui.text_disabled(entry.note)
        imgui.pop_text_wrap_pos()
        imgui.table_next_column()
        if entry.insert:
            imgui.push_id("ins_{0}_{1}".format(section.title, index))
            if imgui.small_button("Insert"):
                self._insert_expression(entry.insert)
            if imgui.is_item_hovered():
                imgui.set_tooltip("Append {0} to the Functions expression".format(entry.insert))
            imgui.pop_id()


def _chord_text(spec: str) -> str:
    """Format a chord spec for display, degrading to the spec itself if it will not parse."""
    try:
        return keys.format(keys.parse(spec))
    except ValueError:  # pragma: no cover - the specs here are literals
        return spec
