def _fallback_doc(name: str, value: Any) -> Tuple[str, str, str]:
    """Prose for a SAFE_NAMES entry that :data:`_EXPR_DOCS` does not cover.

    Keeps the reference honest when the evaluator gains a name and this table has not
    caught up: introspect the signature, take the docstring's first line, and file it under
    "Other" so the omission is visible rather than the function being invisible.
    """
    if not callable(value):
        return ("Other", name, "Constant.")
    signature = "{0}(…)".format(name)
    try:
        signature = "{0}{1}".format(name, inspect.signature(value))
    except (TypeError, ValueError):
        # numpy ufuncs are C objects with no introspectable signature. Expected.
        pass
    doc = (inspect.getdoc(value) or "").strip().splitlines()
    description = doc[0].strip() if doc else "No description available."
    return ("Other", signature, description)


def _expression_sections() -> Tuple[Section, ...]:
    """Build the Expressions reference by walking :data:`expressions.SAFE_NAMES`.

    The dict drives the rows; :data:`_EXPR_DOCS` only supplies prose. A name in the doc
    table that is no longer in ``SAFE_NAMES`` therefore disappears on its own, and a name
    added to ``SAFE_NAMES`` shows up whether or not anyone documented it.
    """
    grouped: Dict[str, List[Entry]] = {}
    for name, value in expressions.SAFE_NAMES.items():
        group, signature, description = _EXPR_DOCS.get(name) or _fallback_doc(name, value)
        # The signature doubles as the insert snippet: dropping "clip(x, lo, hi)" into the
        # editor leaves the argument names as placeholders to type over, which is more use
        # than a bare "clip(" that does not even parse.
        snippet = signature if callable(value) else name
        grouped.setdefault(group, []).append(
            Entry(label=signature, value=name, note=description, insert=snippet)
        )

    sections: List[Section] = []
    for group in _GROUP_ORDER:
        entries = grouped.pop(group, [])
        if entries:
            sections.append(
                Section(title=group, entries=tuple(entries), insertable=True, value_width=0.0)
            )
    # Any group invented by a future _EXPR_DOCS edit, so a typo'd group name cannot hide
    # rows off the end of _GROUP_ORDER.
    for group in sorted(grouped):
        sections.append(
            Section(title=group, entries=tuple(grouped[group]), insertable=True, value_width=0.0)
        )
    return tuple(sections)


