@dataclass(frozen=True)
class Entry:
    """One row of a section: a label, a value column, and an optional dimmed note.

    The meaning of ``value`` is per-tab: a formatted chord in Keyboard, a signature in
    Expressions, a key name in Panels. ``insert`` is the Expressions tab's payload -- the
    text its "Insert" button drops into the Functions panel; an empty string means the row
    has no button.
    """

    label: str
    value: str = ""
    note: str = ""
    insert: str = ""

    def labels(self) -> Tuple[str, ...]:
        """The short fields, matched fuzzily."""
        return (self.label, self.value)

    def prose(self) -> Tuple[str, ...]:
        """The long fields, matched by substring (see :meth:`HelpPanel._matches`)."""
        return (self.note,)


@dataclass(frozen=True)
class Section:
    """A titled group of entries under a collapsing header."""

    title: str
    intro: str = ""
    entries: Tuple[Entry, ...] = ()
    #: Header for the value column. Empty hides the table header row entirely.
    value_header: str = ""
    #: Fixed width of the value column, in points.
    value_width: float = _KEY_COLUMN_W
    #: True for the Expressions tab, whose rows carry an Insert button.
    insertable: bool = False


@dataclass(frozen=True)
class Step:
    """One numbered step of the Getting Started tour, with a button that really runs it.

    ``action_id`` is tried against the workspace's registry first, so the button does
    exactly what the equivalent shortcut does. ``panel`` is the fallback for a workspace
    whose registry does not (yet) carry that id -- opening the panel is always meaningful,
    and a Help button that silently does nothing is worse than no button.
    """

    title: str
    body: str
    button: str
    action_id: Optional[str] = None
    panel: Optional[str] = None


