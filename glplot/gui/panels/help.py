"""The Help panel: a taught tour of the workstation, generated from the real thing.

The architectural rule of this module is that **help content is data**. Every tab is a
list of :class:`Section`/:class:`Entry`/:class:`Step` records rendered by one small set of
generic drawing functions. Nothing here is a wall of hand-inlined ``imgui.text`` calls,
because that shape of code is what makes a Help panel rot: it is too expensive to edit, so
nobody edits it, and within a release it is lying to the user.

Two tabs are not authored at all, they are *derived*:

* **Keyboard** is generated from :class:`~glplot.gui.actions.ActionRegistry` -- titles,
  categories and chords come straight out of the registry the keymap dispatches from, so a
  rebound or renamed action updates Help for free and a hand-written list cannot drift out
  of sync. Registry conflicts (:meth:`~glplot.gui.actions.ActionRegistry.conflicts`) are
  surfaced here too: a chord bound twice is a silently dead binding otherwise.
* **Expressions** is generated by walking :data:`glplot.gui.expressions.SAFE_NAMES`, the
  same dict the evaluator's allowlist is built from. :data:`_EXPR_DOCS` supplies prose for
  each name; a name present in ``SAFE_NAMES`` but missing from the doc table still renders
  (signature introspected, description taken from the docstring), so adding a function to
  the evaluator can never silently drop it out of the reference.

The engine's own hotkeys are the one hand-transcribed list, because they have no registry:
their source of truth is ``glplot/engine.py::_on_key`` and they are copied from it. See
:data:`_ENGINE_HOTKEYS`.
"""

